def norm(s: str) -> str:
    return " ".join(s.split())


def patch(path: pathlib.Path, table: dict[str, tuple[str, str]],
          check: bool) -> tuple[int, list[str]]:
    src = original = htmlio.read(path)
    done, missing = 0, []
    for slug, (old, new) in table.items():
        old, new = norm(old), norm(new)
        if new in src:          # уже применено — скрипт идемпотентен
            done += 1
            continue
        if old not in src:      # лид этой страницы живёт в другом файле
            missing.append(slug)
            continue
        src = src.replace(old, new, 1)
        done += 1
    if not check and src != original:
        htmlio.write(path, src)
    return done, missing


def main() -> int:
    check = "--check" in sys.argv
    problems: list[str] = []

    # Статьи блога лежат в двух файлах: часть в data_rf.py, часть в
    # data_blog_base.py. Пробуем оба и ругаемся, только если лид не нашёлся
    # нигде — иначе «не найден» сработает на каждый лид из соседнего файла.
    todo = dict(BLOG_LEADS)
    for path in (ROOT / "data_rf.py", ROOT / "data_blog_base.py"):
        done, missing = patch(path, todo, check)
        print("%-19s лидов статей обновлено: %d" % (path.name, done))
        todo = {k: v for k, v in todo.items() if k in missing}
    problems += ["лид не найден ни в одном файле данных: %s" % s for s in todo]

    done, missing = patch(ROOT / "data_cat.py", CAT_LEADS, check)
    print("%-19s лидов разделов обновлено: %d из %d" % ("data_cat.py", done, len(CAT_LEADS)))
    problems += ["data_cat.py: не найден старый лид %s" % s for s in missing]

    for p in problems:
        print("  ОШИБКА:", p)
    print("оставлено без числа (нечего взять со страницы): %d" % len(SKIPPED))
    return 1 if problems else 0


