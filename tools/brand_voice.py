"""Бренд в цитируемых фрагментах (GEO): intro-абзац страницы и ответы FAQ.

Зачем. Нейросеть режет страницу на куски и берёт ответ из одного куска. Если в
куске не сказано, КТО оказывает услугу, цитата приводит читателя к конкуренту.
Поэтому в двух местах, откуда цитируют чаще всего (абзац-lead и ответ FAQ),
бренд назван по имени.

Как. Тексты написаны вручную и все разные, массово переписывать их нельзя.
Правил два, оба точечные:
  1. Если в тексте уже стоит глагол от первого лица («рассчитаем», «подадим») —
     подлежащее называем по имени: «КРАН365 рассчитает». Смысл не меняется,
     голос «мы» из текста просто получает адресата.
  2. Если глагола нет, а вопрос про условия оказания услуги (цена, срок подачи,
     география, состав смены) — добавляется одно итоговое предложение. Все
     утверждения в нём уже есть на сайте: перезвон за 15 минут и «оператор и
     топливо в смене» стоят в форме заявки и в блоке «Что входит в стоимость».
Вопросы по нормам и справочные («какая охранная зона», «чем вылет отличается
от высоты») не трогаем: бренд там был бы переспамом, а не ответом.

Функции чистые и детерминированные (вариант фразы выбирается по хэшу текста),
поэтому сборка воспроизводима, а JSON-LD и видимый HTML получают один и тот же
текст.
"""
