def _pick(options, seed: str) -> str:
    h = int(hashlib.md5(seed.encode("utf-8")).hexdigest(), 16)
    return options[h % len(options)]


def _text(s: str) -> str:
    return re.sub(r"<[^>]+>", "", s)


def _has_brand(s: str) -> bool:
    return BRAND.lower() in s.lower()


def _end_with_period(s: str) -> str:
    t = _text(s).rstrip()
    return s if (not t or t[-1] in ".!?…:;") else s.rstrip() + "."


_POSS_RE = re.compile(
    r"(?<![\w-])наш(?:у|а|е|и|его|ей|ем|им|ими|их|ей)?\s+"
    r"(стоимост\w+|парк\w*|сет\w+|цен\w+|ставк\w+|тариф\w*|диспетчер\w*|менеджер\w*|"
    r"специалист\w*|операторы|оператор\w*|машин\w+|техник\w+|прайс\w*|смен\w+)", re.I)


def _swap_poss(s: str) -> str | None:
    found = list(_POSS_RE.finditer(s))
    if len(found) != 1:
        return None
    m = found[0]
    return s[: m.start()] + m.group(1) + " " + BRAND + s[m.end():]


def _swap_verb(s: str) -> str | None:
    """Единственный глагол «мы …» → «КРАН365 …»; если глаголов несколько — None."""
    found = list(_VERB_RE.finditer(s))
    if len(found) != 1:
        return None
    m = found[0]
    return s[: m.start()] + BRAND + " " + _VERBS[m.group(1).lower()] + s[m.end():]


def brand_answer(question: str, answer: str) -> str:
    """Ответ FAQ с названным брендом (или без изменений, если бренд там не к месту)."""
    if _has_brand(answer):
        return answer
    swapped = _swap_verb(answer) or _swap_poss(answer)
    if swapped is not None:
        return swapped
    if not _SVC_RE.search(question) or _REF_RE.search(question) or _CTA_RE.search(answer):
        return answer
    if _INCL_RE.search(question):
        tail = _pick(_TAIL_INCL, question)
    elif _PRICE_RE.search(question):
        tail = _pick(_TAIL_PRICE, question)
    elif _TIME_RE.search(question):
        tail = _pick(_TAIL_TIME, question)
    else:
        tail = _pick(_TAIL_SCOPE, question)
    return _end_with_period(answer) + " " + tail


def brand_lead(lead_html: str, commercial: bool) -> str:
    """Содержимое <p class="lead">…</p> (без тегов абзаца) с названным брендом.

    commercial=False (статьи, справка) — только замена глагола: итоговое
    предложение про смену и перезвон в статье о нормах было бы лишним.
    """
    if _has_brand(lead_html):
        return lead_html
    swapped = _swap_verb(lead_html)
    if swapped is not None:
        return swapped
    if not commercial:
        return lead_html
    t = _text(lead_html).rstrip()
    if not t or t.endswith(":") or len(re.findall(r"[\w'’-]+", t)) > 68:
        return lead_html
    return _end_with_period(lead_html) + " " + _pick(_LEAD_TAILS, t)


def service_faq(h1: str, price: str | None, seed: str) -> tuple[str, str]:
    """Вопрос+ответ «сколько стоит и как заказать» для страниц, где FAQ чисто технический.

    h1 — заголовок страницы без разметки; price — цена из плашки героя («21 390 ₽») или None.
    Все утверждения те же, что в блоке условий цен и в форме заявки на сайте:
    оператор и топливо в смене, подача отдельно, цена и срок — за 15 минут.
    """
    subj = re.sub(r"^Аренда:\s*", "", h1.strip())
    subj = re.sub(r"\s+в Москве и области$", "", subj)
    if re.match(r"Аренда\b", subj):
        q = "Сколько стоит %s и как заказать?" % (subj[0].lower() + subj[1:])
    else:
        q = "Сколько стоит и как заказать: %s?" % subj
    head = subj[0].upper() + subj[1:]
    if price:
        price = re.sub(r"^от\s+", "", price.strip())  # плашка героя уже может начинаться с «от»
        a = _pick((
            "%s в КРАН365 — от %s за смену: оператор и топливо входят в стоимость, подача до объекта "
            "считается отдельно. Оставьте заявку на сайте или позвоните — цену на вашу дату и адрес "
            "назовём за 15 минут.",
            "%s в КРАН365 стоит от %s за смену, оператор и топливо уже включены, а подача до объекта "
            "считается отдельно. Заказ — звонок или заявка на сайте: цену на вашу дату и адрес назовём "
            "за 15 минут.",
        ), seed) % (head, price)
    else:
        a = _pick((
            "%s в КРАН365 считается под объект: оператор и топливо входят в смену, подача до объекта — "
            "отдельно. Оставьте заявку на сайте или позвоните — цену на вашу дату и адрес назовём "
            "за 15 минут.",
            "%s: в КРАН365 заказ — звонок или заявка на сайте, цену на вашу дату и адрес назовём "
            "за 15 минут; оператор и топливо входят в смену.",
        ), seed) % (head,)
    return q, a
